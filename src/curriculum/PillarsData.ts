export function createInitialMastery(baseVal = 32): Record<IqPillarId, number> {
  return IQ_PILLARS.reduce(
    (acc, p) => {
      acc[p.id] = baseVal;
      return acc;
    },
    {} as Record<IqPillarId, number>
  );
}

export function getPillarMeta(id: IqPillarId): IqPillarMeta {
  return IQ_PILLARS.find((p) => p.id === id) ?? IQ_PILLARS[0];
}
