import { PlayBlueprint, SkaterBlueprint, SkaterRole } from '../types/hockey';

const deg = (d: number): number => (d * Math.PI) / 180;

export function makeSkaterBp(
  id: string,
  role: SkaterRole,
  team: 'HOME' | 'AWAY',
  x0: number,
  y0: number,
  x1: number,
  y1: number,
  hipDeg?: number,
  stickDeg?: number,
  bait = false
): SkaterBlueprint {
  return {
    id,
    label: role,
    role,
    team,
    start: { x: x0, y: y0 },
    rollInTo: { x: x1, y: y1 },
    hipCommitAngle: hipDeg !== undefined ? deg(hipDeg) : undefined,
    stickLaneAngle: stickDeg !== undefined ? deg(stickDeg) : undefined,
    deceptionSweep: bait,
  };
}

