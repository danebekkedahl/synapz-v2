export const SEED_PLAY_LIBRARY: PlayBlueprint[] = [
  ...DEFENSIVE_AND_TRANSITION_PLAYS,
  ...OFFENSIVE_AND_SPECIAL_PLAYS,
];

export function getPlaysForPillar(
  pillar: IqPillarId | null,
  customPlays: PlayBlueprint[] = []
): PlayBlueprint[] {
  const all = [...customPlays, ...SEED_PLAY_LIBRARY];
  if (!pillar) return all;
  const filtered = all.filter((p) => p.pillar === pillar);
  return filtered.length > 0 ? filtered : all;
}
